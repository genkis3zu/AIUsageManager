'use strict';
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'streamdeck');
const output = path.join(root, 'build', 'streamdeck', 'io.github.genkis3zu.aiusagemanager.sdPlugin');
// Start clean so the package allowlist sees only files from this build.
fs.rmSync(output, { recursive: true, force: true });
for (const dir of ['bin', 'ui', 'imgs']) fs.mkdirSync(path.join(output, dir), { recursive: true });

// Small fixed CommonJS bundle; module ids match the require() strings used in the sources.
const modules = [
  ['./pipe', 'streamdeck/src/pipe.js'], ['./state', 'streamdeck/src/state.js'], ['./settings', 'streamdeck/src/settings.js'],
  ['./render', 'streamdeck/src/render.js'], ['./location', 'streamdeck/src/location.js'], ['./streamdeck', 'streamdeck/src/streamdeck.js'],
  ['./plugin', 'streamdeck/src/plugin.js'], ['../../obsidian/src/usage', 'obsidian/src/usage.js'],
];
const definitions = modules.map(([id, file]) => `${JSON.stringify(id)}:function(module,exports,require){\n${fs.readFileSync(path.join(root, file), 'utf8')}\n}`).join(',\n');
const bundle = `'use strict';\n// AI Usage Manager Stream Deck plugin; MIT. Generated by tools/build-streamdeck.cjs.\n` +
  `const modules={${definitions}},cache={};\n` +
  `function localRequire(id){if(!Object.prototype.hasOwnProperty.call(modules,id))return require(id);if(!cache[id]){const m={exports:{}};cache[id]=m;modules[id](m,m.exports,localRequire);}return cache[id].exports;}\n` +
  `const plugin=localRequire('./plugin');\nmodule.exports=plugin;\nif(require.main===module)plugin.main();\n`;
fs.writeFileSync(path.join(output, 'bin', 'plugin.cjs'), bundle);

for (const file of ['manifest.json', 'ui/settings.html', 'ui/settings.js', 'imgs/category.svg', 'imgs/action.svg', 'imgs/key.svg'])
  fs.copyFileSync(path.join(source, file), path.join(output, file));
fs.copyFileSync(path.join(root, 'assets', 'app.svg'), path.join(output, 'imgs', 'plugin.svg'));
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(output, 'LICENSE'));
console.log('Built Stream Deck plugin: ' + path.relative(root, output));
